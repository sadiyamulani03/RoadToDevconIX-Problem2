import type { GenerationInfo } from "@/lib/domain/schema";

export default function GenerationProvenance({ generation }: { generation: GenerationInfo | null }) {
  if (!generation) return null;

  return (
    <p className="provenance" data-testid="generation-provenance">
      {generation.mode === "llm" ? (
        <>
          Generated by <strong>{generation.provider}</strong> in {generation.requests} request
          {generation.requests === 1 ? "" : "s"} (timeout and retries enforced server-side).
        </>
      ) : (
        <>
          Generated by the <strong>offline heuristic fallback</strong> ({generation.provider}). No LLM
          was called; no model output is being simulated. Configure LLM_API_KEY to use a model.
        </>
      )}
    </p>
  );
}
