import type { MarketStatus } from "@/lib/domain/schema";

const LABELS: Record<MarketStatus, string> = {
  draft: "Draft",
  approved: "Approved for publication",
  discarded: "Discarded",
};

export function StatusBadge({ status }: { status: MarketStatus }) {
  return <span className={`badge badge-${status}`}>{LABELS[status]}</span>;
}

export interface GenerationBadgeProps {
  mode: "llm" | "heuristic";
  model: string | null;
  fallbackReason: "no_api_key" | "forced_heuristic" | null;
}

export function GenerationBadge({ mode, model, fallbackReason }: GenerationBadgeProps) {
  if (mode === "llm") {
    return (
      <span className="badge badge-llm" title={`Drafts are generated by the configured LLM: ${model ?? "unknown model"}`}>
        LLM · {model ?? "configured model"}
      </span>
    );
  }
  const reason =
    fallbackReason === "forced_heuristic"
      ? "forced by LLM_PROVIDER"
      : "no LLM_API_KEY configured";
  return (
    <span
      className="badge badge-heuristic"
      title={`Offline deterministic fallback (${reason}). No model is being called and no hardcoded market is being presented as model output.`}
    >
      Offline heuristic fallback — {reason}
    </span>
  );
}
